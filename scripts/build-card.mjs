// Bundles apps/mcp-server/ui/card.ts into one self-contained HTML string (no network access, so no CSP exceptions are needed)
// and writes apps/mcp-server/src/ui/card.generated.ts. Run `npm run build:card` after editing the card; a test fails if it is stale.
import { build } from 'esbuild';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const CSS = `
:root{color-scheme:light dark}
*{box-sizing:border-box}
body{margin:0;font:22px/1.4 system-ui,-apple-system,"Segoe UI",sans-serif;background:#fff;color:#14141a}
.card{min-height:100vh;padding:20px 24px;border-left:14px solid #767680}
.card.hold{border-color:#c62828;background:#fff5f5}.card.caution{border-color:#b26a00;background:#fff8e6}.card.allow{border-color:#1b7f3b;background:#f1faf3}
.badge{display:inline-block;font-weight:700;font-size:20px;letter-spacing:.02em;padding:4px 12px;border-radius:999px;background:#14141a;color:#fff}
.hold .badge{background:#c62828}.caution .badge{background:#8a5300}.allow .badge{background:#1b7f3b}
.headline{margin:14px 0 8px;font-size:26px;font-weight:650}
.flags{margin:0 0 10px;padding-left:1.2em}.flags li{margin:2px 0}
.advice{margin:8px 0;font-weight:600}.footer{margin:12px 0 0;font-size:19px;opacity:.85}
@media (prefers-color-scheme:dark){body{background:#101014;color:#f2f2f6}.card.hold{background:#2a1214}.card.caution{background:#2a2110}.card.allow{background:#10231a}}
`;

export async function buildCardHtml() {
  const result = await build({
    entryPoints: [join(root, 'apps/mcp-server/ui/card.ts')],
    bundle: true, write: false, minify: true, format: 'iife', target: 'es2022', platform: 'browser', legalComments: 'none',
  });
  const js = result.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
  return `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Second Opinion</title><style>${CSS}</style></head><body><main id="card" class="card caution" role="status" aria-live="polite"><div class="badge">Checking</div><p class="headline">Checking with Second Opinion...</p></main><script>${js}</script></body></html>`;
}

export function generatedSource(html) {
  return `// GENERATED by scripts/build-card.mjs from apps/mcp-server/ui/card.ts. Do not edit; run \`npm run build:card\`.
export const CARD_HTML = ${JSON.stringify(html)};
`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const html = await buildCardHtml();
  mkdirSync(join(root, 'apps/mcp-server/src/ui'), { recursive: true });
  writeFileSync(join(root, 'apps/mcp-server/src/ui/card.generated.ts'), generatedSource(html));
  console.log(`card.generated.ts written (${html.length} bytes)`);
}
